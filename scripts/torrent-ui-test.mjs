import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, channel: process.env.CHROME_CHANNEL || 'msedge' });
try {
  for (const [width, height] of [[1920,1080], [1280,800], [1280,720], [800,600], [640,480]]) {
    const page = await browser.newPage({ viewport: { width, height }, hasTouch: width <= 1280 });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve('.work/preview/index.html')).href);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('button', { name: 'BitTorrent', exact: true }).click();
    const seed = page.getByRole('button', { name: 'Seed after downloading: Off', exact: true });
    await seed.focus(); await page.keyboard.press('Enter');
    const ratio = page.getByLabel('Seed ratio limit', { exact: true });
    await ratio.fill('0');
    assert.ok(await page.getByRole('button', { name: 'Save settings', exact: true }).isDisabled());
    await ratio.fill('1,5');
    await page.getByRole('button', { name: 'Save settings', exact: true }).click();
    assert.equal(await page.evaluate(() => window.previewState.settings.bt_seed), true);
    assert.equal(await page.evaluate(() => window.previewState.settings.bt_seed_ratio), 1.5);
    await page.getByRole('button', { name: /Add download/ }).first().click();
    await page.getByLabel('Download link', { exact: true }).fill('magnet:?xt=urn:btih:' + 'a'.repeat(40));
    await page.getByRole('button', { name: 'Add to queue', exact: true }).click();
    await page.getByRole('heading', { name: 'Choose torrent files', exact: true }).waitFor();
    await page.locator('.dd-torrent-file').first().waitFor();
    assert.equal(await page.locator('.dd-torrent-file').count(), 100);
    await page.getByRole('button', { name: 'Clear selection', exact: true }).click();
    assert.ok(await page.getByRole('button', { name: 'Download selected', exact: true }).isDisabled());
    const first = page.locator('.dd-torrent-file').first();
    await first.focus(); await page.keyboard.press('Enter');
    assert.equal(await first.getAttribute('aria-pressed'), 'true');
    const direction = button => page.evaluate(button => document.activeElement.dispatchEvent(new CustomEvent('dd-gamepad', { bubbles:true, cancelable:true, detail:{button} })), button);
    await direction(10);
    assert.ok(await page.locator('.dd-torrent-file').nth(1).evaluate(el => el === document.activeElement));
    await page.locator('.dd-torrent-file').last().focus();
    await direction(9);
    assert.ok(await page.locator('.dd-torrent-file').nth(98).evaluate(el => el === document.activeElement));
    await page.getByRole('button', { name: 'Next page', exact: true }).click();
    const next = page.locator('.dd-torrent-file').first();
    await next.waitFor();
    if (width <= 1280) await next.tap(); else await next.click();
    await page.getByRole('button', { name: 'Previous page', exact: true }).click();
    assert.equal(await page.locator('.dd-torrent-file').first().getAttribute('aria-pressed'), 'true');
    const submit = page.getByRole('button', { name: 'Download selected', exact: true });
    const box = await submit.boundingBox();
    assert.ok(box.y >= 0 && box.y + box.height <= height, 'Selection action stays on screen');
    assert.ok(await page.locator('.dd-torrent-files').evaluate(el => el.clientHeight > 40 && el.scrollWidth <= el.clientWidth + 1));
    assert.equal(await page.locator('.dd-torrent-file').evaluateAll(nodes => nodes.filter(e => e.getBoundingClientRect().height < 44).length), 0);
    await page.screenshot({ path: `.work/screenshots/${width}x${height}-torrent-files.png` });
    await submit.click();
    assert.deepEqual(await page.evaluate(() => window.previewTorrentSelection), [1, 101]);
    await page.getByRole('heading', { name: 'Download details', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Pause', exact: true }).click();
    await page.getByRole('button', { name: 'Choose torrent files', exact: true }).click();
    await page.locator('.dd-torrent-file').first().waitFor();
    assert.equal(await page.locator('.dd-torrent-file').first().getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('.dd-torrent-file').nth(1).getAttribute('aria-pressed'), 'false');
    assert.deepEqual(errors, []);
    await page.close();
    console.log(`PASS torrent files/settings: ${width}x${height}`);
  }
} finally { await browser.close(); }
